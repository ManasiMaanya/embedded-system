"""Write a self-contained HTML preview of a Markdown doc and open it in the browser.

Reusable: any .md path, optional --out, --no-open. Default file is docs/architecture.md.
"""

from __future__ import annotations

import argparse
import json
import sys
import webbrowser
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]


def parse_args(argv: list[str]) -> argparse.Namespace:
    p = argparse.ArgumentParser(
        description="Render a Markdown file to HTML (GFM + optional KaTeX/mermaid) and open it."
    )
    p.add_argument(
        "markdown",
        nargs="?",
        default="docs/architecture.md",
        help="path relative to repo root, or absolute (default: docs/architecture.md)",
    )
    p.add_argument(
        "-o",
        "--out",
        type=Path,
        default=None,
        help="HTML output path (default: docs/_preview.html)",
    )
    p.add_argument(
        "--no-open",
        action="store_true",
        help="write HTML only; do not launch a browser",
    )
    return p.parse_args(argv)


def resolve_md(rel: str | Path) -> Path:
    src = Path(rel)
    if not src.is_absolute():
        src = REPO / src
    return src.resolve()


def render_html(src: Path, md: str) -> str:
    payload = json.dumps(md)
    title = src.name.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    path_note = src.as_posix().replace("&", "&amp;").replace("<", "&lt;")
    return f"""<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="utf-8"/>
  <title>{title}</title>
  <link rel="stylesheet" href="https://cdn.jsdelivr.net/npm/katex@0.16.11/dist/katex.min.css"/>
  <style>
    body {{ font-family: Segoe UI, system-ui, sans-serif; max-width: 52rem; margin: 2rem auto; padding: 0 1rem; line-height: 1.45; }}
    pre, code {{ font-family: Consolas, Cascadia Mono, monospace; }}
    pre {{ background: #f4f4f4; padding: 0.75rem; overflow: auto; }}
    table {{ border-collapse: collapse; }}
    td, th {{ border: 1px solid #ccc; padding: 0.35rem 0.55rem; }}
    .mermaid {{ background: #fff; }}
  </style>
</head>
<body>
  <p style="color:#666;font-size:0.9rem">{path_note} — generated by scripts/preview_md.py</p>
  <div id="content">Loading…</div>
  <script src="https://cdn.jsdelivr.net/npm/marked@14.1.3/marked.min.js"></script>
  <script src="https://cdn.jsdelivr.net/npm/katex@0.16.11/dist/katex.min.js"></script>
  <script src="https://cdn.jsdelivr.net/npm/katex@0.16.11/dist/contrib/auto-render.min.js"></script>
  <script src="https://cdn.jsdelivr.net/npm/mermaid@11/dist/mermaid.min.js"></script>
  <script>
    const md = {payload};
    document.getElementById("content").innerHTML = marked.parse(md, {{ gfm: true }});
    renderMathInElement(document.getElementById("content"), {{
      delimiters: [
        {{left: "$$", right: "$$", display: true}},
        {{left: "$", right: "$", display: false}}
      ],
      throwOnError: false
    }});
    mermaid.initialize({{ startOnLoad: false }});
    document.querySelectorAll("pre code.language-mermaid").forEach((code) => {{
      const div = document.createElement("div");
      div.className = "mermaid";
      div.textContent = code.textContent;
      code.parentElement.replaceWith(div);
    }});
    mermaid.run({{ querySelector: ".mermaid" }});
  </script>
</body>
</html>
"""


def main(argv: list[str] | None = None) -> int:
    args = parse_args(sys.argv[1:] if argv is None else argv)
    src = resolve_md(args.markdown)
    if not src.is_file():
        print(f"not found: {src}", file=sys.stderr)
        return 1
    out = args.out if args.out is not None else REPO / "docs" / "_preview.html"
    if not out.is_absolute():
        out = REPO / out
    html = render_html(src, src.read_text(encoding="utf-8"))
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(html, encoding="utf-8")
    print(out)
    if not args.no_open:
        webbrowser.open(out.as_uri())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
